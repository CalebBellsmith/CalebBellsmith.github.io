"""Generate an OpenFOAM double-body (no free surface) RANS case for the canoe.

Full scale, fresh water at 20 C, steady simpleFoam with k-omega SST and
Spalding wall functions. The waterline plane and the centreplane are both
symmetry planes, so only the starboard quarter is meshed (forces x 2).
The bow points toward -x and the flow runs in +x.

    python setup_case.py 1.5            -> cfd/U1.5/
    python setup_case.py 1.5 --draft 115

Run with ./Allrun inside the case (needs the `openfoam` launcher).
"""
import argparse
import os
import shutil
import sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import hull  # noqa: E402

NU = 1.004e-6
RHO = 998.2
NPROC = 8

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Nomad 17 canoe, generated by canoe-cad/cfd/setup_case.py
\\*---------------------------------------------------------------------------*/
FoamFile {{ version 2.0; format ascii; class {cls}; object {obj}; }}
"""


def write(case, rel, cls, obj, body):
    p = os.path.join(case, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w') as fh:
        fh.write(HEADER.format(cls=cls, obj=obj) + body)


def hull_stl(path, draft_mm, nx=361, ns=121):
    """Both sides of the outside-of-wood surface, metres, waterline at z=0,
    bow toward -x."""
    t = np.linspace(-1, 1, nx)
    xs = hull.H * np.sign(t) * (1 - (1 - np.abs(t)) ** 1.6)
    sig = np.linspace(0, 1, ns)
    X, Sg = np.meshgrid(xs, sig, indexing='ij')
    tris = []
    for side in (1, -1):
        P = hull.surface(X, Sg * hull.girth(X), side) / 1000.0
        P[..., 0] *= -1                       # bow to -x
        P[..., 2] -= draft_mm / 1000.0
        for i in range(nx - 1):
            for j in range(ns - 1):
                a, b, c, d = P[i, j], P[i + 1, j], P[i + 1, j + 1], P[i, j + 1]
                tris += [(a, b, c), (a, c, d)]
    with open(path, 'w') as fh:
        fh.write('solid hull\n')
        for a, b, c in tris:
            n = np.cross(b - a, c - a)
            nn = np.linalg.norm(n)
            if nn < 1e-14:
                continue
            n /= nn
            fh.write(f' facet normal {n[0]:.6e} {n[1]:.6e} {n[2]:.6e}\n  outer loop\n')
            for v in (a, b, c):
                fh.write(f'   vertex {v[0]:.7e} {v[1]:.7e} {v[2]:.7e}\n')
            fh.write('  endloop\n endfacet\n')
        fh.write('endsolid hull\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('U', type=float)
    ap.add_argument('--draft', type=float, default=115.0)
    ap.add_argument('--iters', type=int, default=1500)
    a = ap.parse_args()
    U, T = a.U, a.draft
    case = os.path.join(HERE, f'U{U:g}')
    if os.path.exists(case):
        shutil.rmtree(case)
    tpl = os.path.join(HERE, 'template')
    if not os.path.isdir(tpl):            # dictionaries borrowed from the motorBike tutorial
        import subprocess
        subprocess.run(['openfoam', '-c', f'cp -r "$FOAM_TUTORIALS/incompressible/simpleFoam/motorBike" "{tpl}"'], check=True)
    for d in ('system', 'constant', '0.orig'):
        shutil.copytree(os.path.join(tpl, d), os.path.join(case, d))
    for f in ('cuttingPlane', 'streamLines', 'wallBoundedStreamLines', 'ensightWrite',
              'forceCoeffs', 'decomposeParDict-random', 'decomposeParDict.6', 'foamReport',
              'myReportTemplate.md', 'graphFunctionObject', 'topoSetDict', 'profiling'):
        p = os.path.join(case, 'system', f)
        if os.path.exists(p):
            os.remove(p)
    shutil.rmtree(os.path.join(case, 'system', 'finite-area'), ignore_errors=True)
    os.makedirs(os.path.join(case, 'constant', 'triSurface'), exist_ok=True)
    hull_stl(os.path.join(case, 'constant', 'triSurface', 'hull.stl'), T)

    L = hull.L / 1000.0
    xmin, xmax, ymax, zmin = -2.5 * L / 2 - 4.0, L / 2 + 2.5 * L, 5.0, -4.0
    h0 = 0.25
    nx, ny, nz = int(round((xmax - xmin) / h0)), int(round(ymax / h0)), int(round(-zmin / h0))
    write(case, 'system/blockMeshDict', 'dictionary', 'blockMeshDict', f"""
scale 1;
vertices
(
    ({xmin} 0 {zmin}) ({xmax} 0 {zmin}) ({xmax} {ymax} {zmin}) ({xmin} {ymax} {zmin})
    ({xmin} 0 0) ({xmax} 0 0) ({xmax} {ymax} 0) ({xmin} {ymax} 0)
);
blocks ( hex (0 1 2 3 4 5 6 7) ({nx} {ny} {nz}) simpleGrading (1 1 1) );
edges ();
boundary
(
    inlet   {{ type patch; faces ((0 4 7 3)); }}
    outlet  {{ type patch; faces ((1 2 6 5)); }}
    side    {{ type patch; faces ((3 7 6 2)); }}
    bottom  {{ type patch; faces ((0 3 2 1)); }}
    centre  {{ type symmetryPlane; faces ((0 1 5 4)); }}
    surface {{ type symmetryPlane; faces ((4 5 6 7)); }}
);
""")
    write(case, 'system/surfaceFeatureExtractDict', 'dictionary', 'surfaceFeatureExtractDict', """
hull.stl
{
    extractionMethod extractFromSurface;
    includedAngle 150;
    subsetFeatures { nonManifoldEdges no; openEdges yes; }
    writeObj yes;
}
""")
    snappy = open(os.path.join(tpl, 'system', 'snappyHexMeshDict')).read()
    start = snappy.index('geometry')
    end = snappy.index('snapControls')
    snappy = snappy[:start] + f"""geometry
{{
    hull.stl {{ type triSurfaceMesh; name hull; }}
    nearBox {{ type box; min ({-L/2 - 0.3} 0 -0.35); max ({L/2 + 1.5} 0.75 0); }}
    wakeBox {{ type box; min ({-L/2 - 0.8} 0 -0.8); max ({L/2 + 6.0} 1.4 0); }}
}};

castellatedMeshControls
{{
    maxLocalCells 2000000;
    maxGlobalCells 8000000;
    minRefinementCells 10;
    maxLoadUnbalance 0.10;
    nCellsBetweenLevels 3;
    features ( {{ file "hull.eMesh"; level 6; }} );
    refinementSurfaces
    {{
        hull {{ level (6 6); patchInfo {{ type wall; }} }}
    }}
    resolveFeatureAngle 30;
    refinementRegions
    {{
        nearBox {{ mode inside; levels ((1E15 4)); }}
        wakeBox {{ mode inside; levels ((1E15 3)); }}
    }}
    locationInMesh ({xmax - 1.01} {ymax - 1.01} {zmin + 1.01});
    allowFreeStandingZoneFaces true;
}}

""" + snappy[end:]
    snappy = snappy.replace('"(lowerWall|motorBike).*"', 'hull')
    snappy = snappy.replace('nSurfaceLayers 1;', 'nSurfaceLayers 5;')
    snappy = snappy.replace('expansionRatio 1.0;', 'expansionRatio 1.2;')
    snappy = snappy.replace('finalLayerThickness 0.3;', 'finalLayerThickness 0.4;')
    snappy = snappy.replace('minThickness 0.1;', 'minThickness 0.05;')
    with open(os.path.join(case, 'system', 'snappyHexMeshDict'), 'w') as fh:
        fh.write(snappy)

    write(case, 'system/decomposeParDict', 'dictionary', 'decomposeParDict',
          f'numberOfSubdomains {NPROC};\nmethod scotch;\n')
    write(case, 'constant/transportProperties', 'dictionary', 'transportProperties',
          f'transportModel Newtonian;\nnu {NU};\n')
    k = 1.5 * (0.01 * U) ** 2
    omega = k / (10 * NU)
    fields = dict(
        U=('volVectorField', '[0 1 -1 0 0 0 0]', f'({U} 0 0)',
           'inlet { type fixedValue; value $internalField; }',
           'outlet { type inletOutlet; inletValue uniform (0 0 0); value $internalField; }',
           'hull { type noSlip; }'),
        p=('volScalarField', '[0 2 -2 0 0 0 0]', '0',
           'inlet { type zeroGradient; }',
           'outlet { type fixedValue; value $internalField; }',
           'hull { type zeroGradient; }'),
        k=('volScalarField', '[0 2 -2 0 0 0 0]', f'{k:.4e}',
           'inlet { type fixedValue; value $internalField; }',
           'outlet { type inletOutlet; inletValue $internalField; value $internalField; }',
           'hull { type kqRWallFunction; value $internalField; }'),
        omega=('volScalarField', '[0 0 -1 0 0 0 0]', f'{omega:.4e}',
               'inlet { type fixedValue; value $internalField; }',
               'outlet { type inletOutlet; inletValue $internalField; value $internalField; }',
               'hull { type omegaWallFunction; value $internalField; }'),
        nut=('volScalarField', '[0 2 -1 0 0 0 0]', '0',
             'inlet { type calculated; value $internalField; }',
             'outlet { type calculated; value $internalField; }',
             'hull { type nutUSpaldingWallFunction; value $internalField; }'),
    )
    shutil.rmtree(os.path.join(case, '0.orig'))
    for fld, (cls, dims, val, inlet, outlet, wall) in fields.items():
        far = 'slip' if fld == 'U' else ('zeroGradient' if fld != 'nut' else 'calculated; value $internalField')
        write(case, f'0.orig/{fld}', cls, fld, f"""
dimensions      {dims};
internalField   uniform {val};
boundaryField
{{
    #includeEtc "caseDicts/setConstraintTypes"
    {inlet}
    {outlet}
    {wall}
    side   {{ type {far}; }}
    bottom {{ type {far}; }}
}}
""")

    Aref = 1.0
    write(case, 'system/controlDict', 'dictionary', 'controlDict', f"""
application     simpleFoam;
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {a.iters};
deltaT          1;
writeControl    timeStep;
writeInterval   500;
purgeWrite      0;
writeFormat     binary;
writePrecision  8;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable true;

functions
{{
    forces
    {{
        type            forces;
        libs            (forces);
        writeControl    timeStep;
        writeInterval   1;
        log             yes;
        patches         (hull);
        rho             rhoInf;
        rhoInf          {RHO};
        CofR            (0 0 0);
    }}
    yPlus
    {{
        type            yPlus;
        libs            (fieldFunctionObjects);
        writeControl    writeTime;
    }}
    wallShearStress
    {{
        type            wallShearStress;
        libs            (fieldFunctionObjects);
        patches         (hull);
        writeControl    writeTime;
    }}
    #includeEtc "caseDicts/postProcessing/visualization/surfaces.cfg"
}}
""".replace('    #includeEtc "caseDicts/postProcessing/visualization/surfaces.cfg"\n', ''))

    with open(os.path.join(case, 'Allrun'), 'w') as fh:
        fh.write(f"""#!/bin/sh
cd "${{0%/*}}" || exit
. ${{WM_PROJECT_DIR:?}}/bin/tools/RunFunctions
runApplication surfaceFeatureExtract
runApplication blockMesh
runApplication decomposePar
runParallel snappyHexMesh -overwrite
restore0Dir -processor
runParallel checkMesh -constant
runParallel potentialFoam -writephi
runParallel simpleFoam
runApplication reconstructParMesh -constant
runApplication reconstructPar -latestTime
""")
    os.chmod(os.path.join(case, 'Allrun'), 0o755)
    with open(os.path.join(case, 'case.json'), 'w') as fh:
        import json
        json.dump(dict(U=U, draft_mm=T, nu=NU, rho=RHO, L=hull.L, half_model=True), fh)
    print('case written:', case, f'background {nx}x{ny}x{nz}')


if __name__ == '__main__':
    main()
